def load(conn, diff_points):
    cur = conn.cursor()
    cat_id = {r["name"]: r["id"] for r in cur.execute("SELECT id, name FROM category")}
    subs = {}
    for r in cur.execute("SELECT id, cat_id, name FROM subcategory"):
        subs[(r["cat_id"], r["name"])] = r["id"]

    import re
    from datetime import datetime

    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    for cat, sub, qtype, diff, stem, options, answer, analysis in QUESTIONS:
        cid = cat_id.get(cat)
        sid = subs.get((cid, sub))
        if not cid or not sid:
            continue
        opts = [{"key": "ABCDEF"[i], "text": t} for i, t in enumerate(options)]
        blanks = len(re.findall(r"_{2,}", stem)) if qtype == "fill" else 0
        cur.execute(
            """INSERT INTO question(cat_id, sub_id, qtype, diff, stem, options, answer,
               blanks, score, analysis, tags, created_at, updated_at)
               VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                cid, sid, qtype, diff, stem,
                __import__("json").dumps(opts, ensure_ascii=False),
                answer, max(1, blanks) if qtype == "fill" else 0,
                None, analysis, "示例", ts, ts,
            ),
        )
    conn.commit()
